SELECT 'billing', COUNT(*) FROM FACT_BILLING UNION ALL
SELECT 'pos', COUNT(*) FROM FACT_POS UNION ALL
SELECT 'inventory', COUNT(*) FROM FACT_DIST_INVENTORY;
